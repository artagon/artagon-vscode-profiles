//! Build script for `vsp` that embeds the v2.2 consolidated catalog, presets,
//! 4-tier lockfile, and packs snapshot (including the 7 RTK shell scripts)
//! deterministically into `OUT_DIR/embedded_snapshot.rs`.

use std::env;
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

/// Top-level consolidated schema files required in every release snapshot.
const REQUIRED_FILES: &[&str] = &[
    "catalog/extensions.jsonc",
    "catalog/policy.jsonc",
    "presets.jsonc",
    "vsp.lock.json",
];

fn main() {
    println!("cargo:rerun-if-changed=build.rs");

    let manifest_dir = PathBuf::from(
        env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR must be set by Cargo"),
    );
    let repo_root = manifest_dir
        .parent()
        .and_then(Path::parent)
        .expect("crates/vsp must reside two levels below the repository root")
        .to_path_buf();
    let canon_root = fs::canonicalize(&repo_root)
        .unwrap_or_else(|e| panic!("failed to canonicalize repo root {}: {e}", repo_root.display()));

    let mut entries: Vec<(String, PathBuf)> = Vec::new();
    let mut watched_dirs: Vec<PathBuf> = Vec::new();

    for rel in REQUIRED_FILES {
        let abs = canon_root.join(rel);
        let canon = fs::canonicalize(&abs).unwrap_or_else(|e| {
            panic!(
                "required v2.2 schema file missing or unreadable ({}): {e}",
                abs.display()
            )
        });
        assert!(
            canon.starts_with(&canon_root),
            "required schema file escapes repository root: {}",
            canon.display()
        );
        assert!(
            canon.is_file(),
            "required schema entry is not a regular file: {}",
            canon.display()
        );
        entries.push(((*rel).to_string(), canon));
    }

    let packs_dir = canon_root.join("packs");
    let canon_packs = fs::canonicalize(&packs_dir).unwrap_or_else(|e| {
        panic!(
            "required packs/ directory missing or unreadable ({}): {e}",
            packs_dir.display()
        )
    });
    assert!(
        canon_packs.starts_with(&canon_root) && canon_packs.is_dir(),
        "packs/ must be a directory inside the repository root"
    );

    collect_packs_tree(&canon_root, &canon_packs, &mut watched_dirs, &mut entries);

    // Deterministic LC_ALL=C byte-order sort for reproducible builds.
    watched_dirs.sort_by(|a, b| a.as_os_str().as_encoded_bytes().cmp(b.as_os_str().as_encoded_bytes()));
    entries.sort_by(|a, b| a.0.as_bytes().cmp(b.0.as_bytes()));

    for dir in &watched_dirs {
        println!("cargo:rerun-if-changed={}", dir.display());
    }
    for (_, abs) in &entries {
        println!("cargo:rerun-if-changed={}", abs.display());
    }

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR must be set by Cargo"));
    let dest_path = out_dir.join("embedded_snapshot.rs");

    let mut out = String::new();
    out.push_str("// @generated by crates/vsp/build.rs — DO NOT EDIT.\n");
    out.push_str("/// Deterministically sorted (`LC_ALL=C`) embedded v2.2 schema snapshot.\n");
    out.push_str("pub(super) const EMBEDDED_SNAPSHOT_FILES: &[(&str, &[u8])] = &[\n");
    for (rel, abs) in &entries {
        let abs_str = abs
            .to_str()
            .unwrap_or_else(|| panic!("non-UTF-8 path in snapshot: {}", abs.display()));
        out.push_str(&format!(
            "    ({rel:?}, include_bytes!({abs_str:?})),\n"
        ));
    }
    out.push_str("];\n");

    let mut file = fs::File::create(&dest_path)
        .unwrap_or_else(|e| panic!("failed to create {}: {e}", dest_path.display()));
    file.write_all(out.as_bytes())
        .unwrap_or_else(|e| panic!("failed to write {}: {e}", dest_path.display()));
}

fn collect_packs_tree(
    canon_root: &Path,
    dir: &Path,
    watched_dirs: &mut Vec<PathBuf>,
    entries: &mut Vec<(String, PathBuf)>,
) {
    watched_dirs.push(dir.to_path_buf());

    let mut children: Vec<PathBuf> = fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("failed to read directory {}: {e}", dir.display()))
        .map(|res| res.expect("failed to read directory entry").path())
        .collect();
    children.sort_by(|a, b| {
        a.file_name()
            .expect("entry filename")
            .as_encoded_bytes()
            .cmp(b.file_name().expect("entry filename").as_encoded_bytes())
    });

    for child in children {
        let name = child
            .file_name()
            .and_then(|n| n.to_str())
            .unwrap_or_else(|| panic!("non-UTF-8 entry under packs/: {}", child.display()));
        if name == ".DS_Store" {
            continue;
        }
        let meta = fs::symlink_metadata(&child)
            .unwrap_or_else(|e| panic!("failed to stat {}: {e}", child.display()));
        assert!(
            !meta.file_type().is_symlink(),
            "symlinks are forbidden inside embedded packs/: {}",
            child.display()
        );
        let canon = fs::canonicalize(&child)
            .unwrap_or_else(|e| panic!("failed to canonicalize {}: {e}", child.display()));
        assert!(
            canon.starts_with(canon_root),
            "pack asset escapes repository root: {}",
            canon.display()
        );

        if meta.is_dir() {
            collect_packs_tree(canon_root, &canon, watched_dirs, entries);
        } else if meta.is_file() {
            let rel = canon
                .strip_prefix(canon_root)
                .expect("canonical path must start with repo root");
            let rel_str = rel
                .components()
                .map(|c| {
                    c.as_os_str()
                        .to_str()
                        .unwrap_or_else(|| panic!("non-UTF-8 component in {}", rel.display()))
                })
                .collect::<Vec<_>>()
                .join("/");
            entries.push((rel_str, canon));
        } else {
            panic!("unsupported non-regular file in packs/: {}", child.display());
        }
    }
}
